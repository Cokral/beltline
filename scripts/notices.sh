#!/bin/sh
# Writes THIRD_PARTY_NOTICES: the license of every Go module compiled into beltlined, every npm
# package bundled into the web app, and the fonts the web app embeds. Run it after a dependency
# change and commit the result; `scripts/notices.sh --check` fails when the file is out of date.
# Needs Web/node_modules (cd Web && npm ci).
# Usage: scripts/notices.sh [--check]
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
output="$root/THIRD_PARTY_NOTICES"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT INT TERM

# license_file prints the license file in a package folder.
license_file() {
	for name in LICENSE LICENSE.md LICENSE.txt LICENCE COPYING license license.md; do
		if [ -f "$1/$name" ]; then
			echo "$1/$name"
			return 0
		fi
	done
	echo "notices: no license file in $1" >&2
	exit 1
}

# section appends one package's heading and license text.
section() {
	{
		printf '%s\n' "------------------------------------------------------------------------------"
		printf '%s\n\n' "$1"
		cat "$2"
		printf '\n'
	} >>"$work/notices"
}

{
	printf '%s\n\n' "Beltline includes the third-party software listed below, under the licenses that follow each name."
	printf '%s\n\n' "Generated by scripts/notices.sh; do not edit by hand."
} >"$work/notices"

# The Go modules beltlined is built from (the release build, with the web app embedded). The
# embed pattern needs a staged web app to type-check, so list without the tag: it adds no module.
(cd "$root/daemon" && go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/beltlined) |
	sort -u >"$work/go"
while read -r path version dir; do
	section "$path $version (Go module)" "$(license_file "$dir")"
done <"$work/go"

# The npm packages the web app's production bundle is built from.
if [ ! -d "$root/Web/node_modules" ]; then
	echo "notices: Web/node_modules is missing; run (cd Web && npm ci) first" >&2
	exit 1
fi
(cd "$root/Web" && npm ls --omit=dev --all --parseable) | grep '/node_modules/' | sort -u >"$work/npm"
while read -r dir; do
	name=$(node -p "require(process.argv[1]).name + ' ' + require(process.argv[1]).version" "$dir/package.json")
	section "$name (npm package)" "$(license_file "$dir")"
done <"$work/npm"

# The fonts, each under the SIL Open Font License 1.1.
for license in "$root"/Web/src/theme/fonts/OFL-*.txt; do
	font=$(basename "$license" .txt | sed 's/^OFL-//')
	section "$font font (SIL Open Font License 1.1)" "$license"
done

if [ "${1:-}" = "--check" ]; then
	if ! cmp -s "$work/notices" "$output"; then
		echo "notices: THIRD_PARTY_NOTICES is out of date; run scripts/notices.sh" >&2
		exit 1
	fi
	exit 0
fi
cp "$work/notices" "$output"
echo "Wrote $output"
